export function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function escapeXml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

export function safeJsonLd(data) {
  return JSON.stringify(data, null, 2).replace(/</g, '\\u003c');
}

export function renderHeadersFile(securityHeaders) {
  const lines = [
    '# Cloudflare Workers Static Assets headers.',
    '# Generated by sites/build.mjs from crates/sws-security/src/headers.rs SECURITY_HEADERS.',
    '# Verified by core/tools/check-headers.mjs.',
    '/*',
  ];
  for (const [name, value] of securityHeaders) {
    lines.push(`  ${name}: ${value}`);
  }
  lines.push(
    '',
    '/styles.css',
    '  Cache-Control: public, max-age=3600, must-revalidate',
    '',
  );
  return lines.join('\n');
}

export function renderRobotsTxt(baseUrl) {
  return `User-agent: *\nAllow: /\n\nSitemap: ${baseUrl}/sitemap.xml\n`;
}

export function renderSitemapXml(baseUrl, paths) {
  const urls = paths
    .map((p) => {
      const normalized = p.startsWith('/') ? p : `/${p}`;
      return `  <url>\n    <loc>${escapeXml(`${baseUrl}${normalized}`)}</loc>\n  </url>`;
    })
    .join('\n');
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    urls,
    '</urlset>',
    '',
  ].join('\n');
}

