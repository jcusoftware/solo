//! JSON Schema (the subset schemars emits) to TypeScript declaration text.
//!
//! The `.d.ts` is derived from the generated schemas rather than from a second
//! derive, so the types and the schemas cannot disagree.

use std::collections::BTreeMap;

use serde_json::{Map, Value};

/// Render one `.d.ts` file declaring every named type reachable from `roots`.
///
/// Each root is a complete schema document: its own `title` names it and its
/// `$defs` hold the types it references. A type that appears under the same
/// name in several roots must render identically.
pub fn render_declarations(roots: &[Value]) -> Result<String, String> {
    let mut decls: BTreeMap<String, String> = BTreeMap::new();
    for root in roots {
        let Some(obj) = root.as_object() else {
            return Err("root schema is not an object".to_string());
        };
        let title = obj
            .get("title")
            .and_then(Value::as_str)
            .ok_or("root schema has no title")?;
        let mut named: Vec<(String, &Value)> = vec![(title.to_string(), root)];
        if let Some(Value::Object(defs)) = obj.get("$defs") {
            named.extend(defs.iter().map(|(k, v)| (k.clone(), v)));
        }
        for (name, schema) in named {
            let text = render_decl(&name, schema);
            match decls.get(&name) {
                Some(existing) if *existing != text => {
                    return Err(format!(
                        "type `{name}` renders differently in two root schemas"
                    ));
                }
                _ => {
                    decls.insert(name, text);
                }
            }
        }
    }
    let mut out = String::from(
        "// Generated by `npm run codegen` (crates/sws-codegen) from the Rust types.\n\
         // Do not edit: change the Rust types and regenerate.\n\
         // Declarations only; this package ships no JavaScript.\n",
    );
    for text in decls.values() {
        out.push('\n');
        out.push_str(text);
    }
    Ok(out)
}

fn render_decl(name: &str, schema: &Value) -> String {
    let mut out = String::new();
    if let Some(doc) = schema.get("description").and_then(Value::as_str) {
        out.push_str(&jsdoc(doc, ""));
    }
    if is_plain_object(schema) {
        out.push_str(&format!(
            "export interface {name} {}\n",
            render_object_body(schema, 0)
        ));
    } else {
        let body = ts_type(schema, 0);
        let sep = if body.starts_with('\n') { "" } else { " " };
        out.push_str(&format!("export type {name} ={sep}{body};\n"));
    }
    out
}

/// An object schema that should be an `interface` (has `properties`, no union).
fn is_plain_object(schema: &Value) -> bool {
    schema.get("properties").is_some()
        && schema.get("type").is_some_and(|t| t == "object")
        && schema.get("oneOf").is_none()
        && schema.get("anyOf").is_none()
}

fn jsdoc(text: &str, indent: &str) -> String {
    let mut out = format!("{indent}/**\n");
    for line in text.lines() {
        let line = line.replace("*/", "*\\/");
        if line.is_empty() {
            out.push_str(&format!("{indent} *\n"));
        } else {
            out.push_str(&format!("{indent} * {line}\n"));
        }
    }
    out.push_str(&format!("{indent} */\n"));
    out
}

fn ts_type(schema: &Value, depth: usize) -> String {
    let obj = match schema {
        Value::Bool(true) => return "unknown".to_string(),
        Value::Bool(false) => return "never".to_string(),
        Value::Object(o) if o.is_empty() => return "unknown".to_string(),
        Value::Object(o) => o,
        _ => return "unknown".to_string(),
    };
    if let Some(Value::String(r)) = obj.get("$ref") {
        return r.rsplit('/').next().unwrap_or("unknown").to_string();
    }
    if let Some(c) = obj.get("const") {
        return c.to_string();
    }
    if let Some(Value::Array(values)) = obj.get("enum") {
        return values
            .iter()
            .map(Value::to_string)
            .collect::<Vec<_>>()
            .join(" | ");
    }
    for key in ["oneOf", "anyOf"] {
        if let Some(Value::Array(branches)) = obj.get(key) {
            let multi = branches.iter().any(|b| b.get("properties").is_some());
            let d = if multi { depth + 1 } else { depth };
            let parts = branches.iter().map(|b| ts_type(b, d)).collect();
            return union(parts, depth, multi);
        }
    }
    if let Some(Value::Array(parts)) = obj.get("allOf") {
        return parts
            .iter()
            .map(|p| paren_union(&ts_type(p, depth)))
            .collect::<Vec<_>>()
            .join(" & ");
    }
    match obj.get("type") {
        Some(Value::String(t)) => type_named(t, obj, depth),
        Some(Value::Array(ts)) => union(
            ts.iter()
                .filter_map(Value::as_str)
                .map(|t| type_named(t, obj, depth))
                .collect(),
            depth,
            false,
        ),
        _ if obj.contains_key("properties") => render_object_body(schema, depth),
        _ => "unknown".to_string(),
    }
}

fn type_named(t: &str, obj: &Map<String, Value>, depth: usize) -> String {
    match t {
        "string" => "string".to_string(),
        "integer" | "number" => "number".to_string(),
        "boolean" => "boolean".to_string(),
        "null" => "null".to_string(),
        "array" => render_array(obj, depth),
        "object" => render_object(obj, depth),
        _ => "unknown".to_string(),
    }
}

/// Join union members. `multiline` puts each member on its own `| ` line
/// (used when members are object literals); the result then starts with a
/// newline.
fn union(mut parts: Vec<String>, depth: usize, multiline: bool) -> String {
    parts.dedup();
    if multiline {
        let pad = "  ".repeat(depth + 1);
        return parts
            .iter()
            .map(|p| format!("\n{pad}| {p}"))
            .collect::<String>();
    }
    parts.join(" | ")
}

fn paren_union(t: &str) -> String {
    if t.contains(" | ") {
        format!("({t})")
    } else {
        t.to_string()
    }
}

fn render_array(obj: &Map<String, Value>, depth: usize) -> String {
    let item = obj
        .get("items")
        .map_or_else(|| "unknown".to_string(), |i| ts_type(i, depth));
    let min = obj.get("minItems").and_then(Value::as_u64);
    let max = obj.get("maxItems").and_then(Value::as_u64);
    if let (Some(min), Some(max)) = (min, max)
        && min == max
        && (1..=8).contains(&min)
    {
        let n = usize::try_from(min).unwrap_or(0);
        return format!("[{}]", vec![item; n].join(", "));
    }
    format!("{}[]", paren_union(&wrap_fn(&item)))
}

fn wrap_fn(t: &str) -> String {
    if t.starts_with('{') || t.contains('\n') {
        format!("({t})")
    } else {
        t.to_string()
    }
}

fn render_object(obj: &Map<String, Value>, depth: usize) -> String {
    if obj.contains_key("properties") {
        return render_object_body(&Value::Object(obj.clone()), depth);
    }
    let value = match obj.get("additionalProperties") {
        Some(s @ Value::Object(_)) => ts_type(s, depth),
        _ => match obj.get("patternProperties") {
            Some(Value::Object(p)) if !p.is_empty() => union(
                p.values().map(|s| ts_type(s, depth)).collect(),
                depth,
                false,
            ),
            _ => "unknown".to_string(),
        },
    };
    format!("Record<string, {value}>")
}

fn render_object_body(schema: &Value, depth: usize) -> String {
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let pad = "  ".repeat(depth + 1);
    let mut out = String::from("{\n");
    if let Some(Value::Object(props)) = schema.get("properties") {
        for (key, sub) in props {
            if let Some(doc) = sub.get("description").and_then(Value::as_str) {
                out.push_str(&jsdoc(doc, &pad));
            }
            let opt = if required.contains(&key.as_str()) {
                ""
            } else {
                "?"
            };
            out.push_str(&format!(
                "{pad}{}{opt}: {};\n",
                prop_name(key),
                ts_type(sub, depth + 1)
            ));
        }
    }
    out.push_str(&format!("{}}}", "  ".repeat(depth)));
    out
}

fn prop_name(key: &str) -> String {
    let ident = key.chars().enumerate().all(|(i, c)| {
        c == '_' || c == '$' || c.is_ascii_alphabetic() || (i > 0 && c.is_ascii_digit())
    });
    if ident && !key.is_empty() {
        key.to_string()
    } else {
        Value::String(key.to_string()).to_string()
    }
}
