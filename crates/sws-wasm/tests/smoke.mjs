// Wasm export smoke test (issue #25): actually loads the wasm-bindgen build
// output (crates/sws-wasm/pkg, produced by `run-smoke.sh`) and executes every
// export — compile_site, validate_site, compile_css, validate_css,
// check_contrast — asserting both success shapes and the JsValue error shape
// (a plain string message) on invalid input.
//
// Run via `crates/sws-wasm/run-smoke.sh`; CI runs it in the `wasm-smoke` job.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
// --target nodejs output is CommonJS; the workspace package.json sets
// "type": "module", so run-smoke.sh renames the entry to .cjs (the worker
// crate's ESM snippet loads through Node's require(esm), Node >= 20.19).
const wasm = require('../pkg/sws_wasm.cjs');

// -- compile_site: valid IR -> files/diagnostics report --------------------

const validIr = JSON.stringify({
  schema_version: 1,
  slug: 'acme-studio-demo',
  name: 'Acme Studio',
  locale: 'en-US',
  base_url: 'https://acme.example',
  tokens: {
    colors: { ink: '#1A1A1A', paper: '#FFFFFF' },
    fonts: { body: 'system-ui, sans-serif' },
    contrast_pairs: [
      { foreground: 'ink', background: 'paper', min_ratio: 4.5, usage: 'body' },
    ],
  },
  pages: [
    {
      id: 'home',
      route: { kind: 'static', path: '/' },
      title: 'Home',
      body: [
        {
          type: 'element',
          tag: 'a',
          classes: ['skip-link'],
          attrs: { href: '#main' },
          children: [{ type: 'text', value: 'Skip to main content' }],
        },
        {
          type: 'element',
          tag: 'header',
          children: [{ type: 'text', value: 'Acme Studio' }],
        },
        {
          type: 'element',
          tag: 'main',
          attrs: { id: 'main', tabindex: '-1' },
          children: [
            {
              type: 'element',
              tag: 'h1',
              children: [{ type: 'text', value: 'Acme Studio' }],
            },
          ],
        },
        {
          type: 'element',
          tag: 'footer',
          children: [{ type: 'text', value: 'Acme Studio' }],
        },
      ],
    },
  ],
});

const compiled = JSON.parse(wasm.compile_site(validIr));
assert.ok(typeof compiled.files['index.html'] === 'string' && compiled.files['index.html'].length > 0, 'compile_site emits index.html');
assert.ok(Array.isArray(compiled.diagnostics), 'compile_site returns a diagnostics array');
assert.ok(compiled.index_html_bytes > 0, 'compile_site reports index_html_bytes');
assert.ok(Number.isInteger(compiled.styles_css_bytes), 'compile_site reports styles_css_bytes');
console.log('compile_site: valid IR compiled, index.html present, diagnostics array');

// -- compile_site: invalid IR -> JsValue error shape (string message) ------

assert.throws(
  () => wasm.compile_site('{not valid json'),
  (err) => typeof err === 'string' && err.includes('invalid SiteDocument JSON'),
  'compile_site maps parse failures to a string JsValue error',
);
console.log('compile_site: invalid IR rejected with string JsValue error');

// -- validate_site: valid + invalid IR -------------------------------------

const validated = JSON.parse(wasm.validate_site(validIr));
assert.equal(validated.valid, true, 'validate_site marks valid IR valid');
assert.deepEqual(validated.ir_errors, [], 'validate_site returns no ir_errors for valid IR');
assert.ok(Array.isArray(validated.diagnostics), 'validate_site returns a diagnostics array');

assert.throws(
  () => wasm.validate_site('['),
  (err) => typeof err === 'string' && err.includes('invalid SiteDocument JSON'),
  'validate_site maps parse failures to a string JsValue error',
);
console.log('validate_site: valid + invalid IR paths exercised');

// -- compile_css: Stylesheet JSON -> emitted CSS ----------------------------

const stylesheetJson = JSON.stringify({
  comment_header: 'Generated by SWS. Do not edit.',
  root_vars: { '--bg': '#E9E2D2', '--text': '#241207' },
  media_queries: { sm: '(min-width: 40rem)' },
  rules: [
    {
      selector: 'body',
      breakpoint: null,
      pseudo: null,
      declarations: { background: 'var(--bg)', color: 'var(--text)' },
    },
    {
      selector: '.grid',
      breakpoint: 'sm',
      pseudo: null,
      declarations: { 'grid-template-columns': '1fr 1fr' },
    },
  ],
});

const css = wasm.compile_css(stylesheetJson);
assert.equal(typeof css, 'string', 'compile_css returns CSS text');
assert.ok(css.includes(':root {\n  --bg: #E9E2D2;\n  --text: #241207;\n}'), 'compile_css emits :root vars');
assert.ok(css.includes('body { background: var(--bg); color: var(--text); }'), 'compile_css emits body rule');
assert.ok(css.includes('@media (min-width: 40rem) {\n  .grid { grid-template-columns: 1fr 1fr; }\n}'), 'compile_css emits breakpoint rules');
assert.equal(wasm.compile_css(stylesheetJson), css, 'compile_css output is deterministic');

assert.throws(
  () => wasm.compile_css('{not valid json'),
  (err) => typeof err === 'string' && err.includes('invalid Stylesheet JSON'),
  'compile_css maps JSON errors to a string JsValue error',
);
assert.throws(
  () =>
    wasm.compile_css(
      JSON.stringify({
        comment_header: null,
        root_vars: {},
        media_queries: {},
        rules: [
          {
            selector: 'body',
            breakpoint: null,
            pseudo: null,
            declarations: { color: 'red; background: blue' },
          },
        ],
      }),
    ),
  (err) => typeof err === 'string' && err.includes('CSS emit error'),
  'compile_css sanitizer gate rejects injection payloads with a string JsValue error',
);
console.log('compile_css: valid Stylesheet emitted (deterministic), JSON + sanitizer errors exercised');

// -- validate_css: CSS text -> { valid, diagnostics } -----------------------

const validReport = JSON.parse(wasm.validate_css(css));
assert.equal(validReport.valid, true, 'validate_css accepts emitted CSS');
assert.deepEqual(validReport.diagnostics, [], 'validate_css returns no diagnostics for valid CSS');

const invalidReport = JSON.parse(wasm.validate_css('body { color: '));
assert.equal(invalidReport.valid, false, 'validate_css marks malformed CSS invalid');
assert.ok(Array.isArray(invalidReport.diagnostics) && invalidReport.diagnostics.length >= 1, 'validate_css returns a diagnostics array on error');
assert.equal(invalidReport.diagnostics[0].level, 'error', 'parse failure is error-level');
assert.equal(invalidReport.diagnostics[0].code, 'css_parse_error', 'parse failure carries css_parse_error code');
assert.ok(invalidReport.diagnostics[0].message.includes('CSS parse error'), 'diagnostic message carries parser detail');
console.log('validate_css: valid + invalid CSS text exercised, diagnostic shape asserted');

// -- check_contrast: AA pass/fail + invalid color ---------------------------

assert.ok(wasm.check_contrast('#1A1A1A', '#FFFFFF') >= 4.5, 'check_contrast flags AA-passing pair');
assert.ok(Math.abs(wasm.check_contrast('#000000', '#FFFFFF') - 21.0) < 0.05, 'check_contrast returns ~21 for black on white');
assert.throws(
  () => wasm.check_contrast('#XYZ', '#FFFFFF'),
  (err) => typeof err === 'string' && err.includes('invalid #RRGGBB'),
  'check_contrast maps invalid colors to a string JsValue error',
);
console.log('check_contrast: AA evaluation + string JsValue error exercised');

console.log('smoke.mjs: all wasm exports executed and asserted');
